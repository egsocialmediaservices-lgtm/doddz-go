  function getLang() {
    return localStorage.getItem('doddz_lang') === 'en' ? 'en' : 'ar';
  }

  function translateTextNode(text, lang) {
    if (lang !== 'en') return text;
    let out = text;
    for (const [ar, en] of phrases) {
      if (out.includes(ar)) out = out.split(ar).join(en);
    }
    return out;
  }

  function walkTranslate(root, lang) {
    if (!root || lang !== 'en') return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node => {
      const parent = node.parentElement;
      if (!parent) return;
      const tag = parent.tagName;
      if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT') return;
      if (parent.closest('[data-no-i18n]')) return;
      const raw = node.nodeValue;
      if (!raw || !raw.trim()) return;
      // skip pure numbers / urls
      if (/^[\d\s.,:%+\-_/\\]+$/.test(raw.trim())) return;
      const next = translateTextNode(raw, lang);
      if (next !== raw) node.nodeValue = next;
    });
  }

  function translateAttributes(root, lang) {
    if (lang !== 'en' || !root) return;
    root.querySelectorAll('[placeholder]').forEach(el => {
      const ph = el.getAttribute('placeholder');
      if (!ph) return;
      const next = translateTextNode(ph, 'en');
      if (next !== ph) el.setAttribute('placeholder', next);
    });
    root.querySelectorAll('[title]').forEach(el => {
      const title = el.getAttribute('title');
      if (!title) return;
      const next = translateTextNode(title, 'en');
      if (next !== title) el.setAttribute('title', next);
    });
  }

