-- ── 5) توحيد أي اسم قديم فاضل على منتجات المنزل ────────────────
--    (بيلمس أي منتج اتضاف بعد المابنج ده وباسم قديم، فالتقسيم ما يتكسرش)
update public.products
   set subcategory = case
         when subcategory in ('ادوات مطبخ', 'مستلزمات حمامات و مطابخ') then 'مستلزمات مطبخ'
         when subcategory in ('صيانة منزلية', 'ادوات صيانة سيارات')     then 'ادوات صيانة'
         else subcategory
       end,
       updated_at = now()
 where section = 'home'
   and subcategory in ('ادوات مطبخ', 'مستلزمات حمامات و مطابخ',
                       'صيانة منزلية', 'ادوات صيانة سيارات');


-- ── 6) الأسماء القديمة «لاب توب» → «اكسسوارات لاب توب» ──────────
--    دة عرض/تسمية بس: عمود `section` يفضل `laptops` زي ما هو.
update public.products
   set category = 'اكسسوارات لاب توب'
 where section = 'laptops'
   and category = 'لاب توب';


