-- 11 — توحيد التصنيفات الفرعية لقسم «المنزل»
-- ================================================================
-- المطلوب: «المنزل» يتقسّم لأربع مجموعات:
--   • مستلزمات مطبخ   • مستلزمات حمام   • ديكور   • ادوات صيانة
--
-- اللي بيحصل هنا:
--   1) تاغ `products.subcategory` لكل منتج في section='home' حسب الـid.
--   2) توحيد أي اسم قديم فاضل على نفس المنتجات
--      («ادوات مطبخ» / «صيانة منزلية» / «مستلزمات حمامات و مطابخ» /
--       «ادوات صيانة سيارات» / «مستلزمات المخيم») على الأسماء الأربعة.
--
-- ⚠️ مفيش أي لمس لـ `section` أو `status` أو `price` أو الصور — يعني
--    المنتجات هتفضل في نفس القسم ونفس حالة الاعتماد ونفس الروابط.
--
-- ⚠️ ليه بنعطّل التريجر بالاسم؟
--    `trg_enforce_seller_product_update` بيرمي
--    «غير مسموح بتعديل منتج مش ملكك» أي `UPDATE products` من SQL Editor
--    لأن `auth.uid()` هناك فاضي. بنعطّله بالاسم جوه نفس الـtransaction
--    ونرجّعه في آخر الملف — أي فشل في أي سطر بيرجّع كل حاجة (التعطيل
--    نفسه بيتراجع). ممنوع `DISABLE TRIGGER ALL` (42501).
--
-- المابنج ده راجعه المستخدم قبل التشغيل — لو عايز ينقل منتج لمجموعة
-- تانية، يغيّر الـid من مجموعة للتانية ويشغّل الملف من أوله تاني.
-- ================================================================

alter table public.products disable trigger trg_enforce_seller_product_update;


